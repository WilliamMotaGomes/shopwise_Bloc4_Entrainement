-- ShopWise : schema relationnel complet (compatible H2 / PostgreSQL).
-- En developpement le schema est genere par Hibernate (ddl-auto=create-drop) ; ce script est la
-- reference pour une base persistante (a rejouer tel quel, ou via Flyway/Liquibase).

-- ---------------------------------------------------------------- PRODUCTS (existant)
CREATE TABLE products (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        VARCHAR(100)   NOT NULL,
    description VARCHAR(500),
    price       NUMERIC(10, 2) NOT NULL CHECK (price > 0),
    created_at  TIMESTAMP,
    updated_at  TIMESTAMP
);

-- ---------------------------------------------------------------- SALES (nouveau)
CREATE TABLE sales (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sale_date    TIMESTAMP      NOT NULL,
    total_amount NUMERIC(12, 2) NOT NULL CHECK (total_amount >= 0)
);
CREATE INDEX idx_sales_sale_date ON sales (sale_date);

-- ---------------------------------------------------------------- SALE_ITEMS (nouveau)
-- unit_price = instantane du prix catalogue au moment de la vente (l'historique n'est jamais reecrit).
CREATE TABLE sale_items (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sale_id    BIGINT         NOT NULL,
    product_id BIGINT         NOT NULL,
    quantity   INTEGER        NOT NULL CHECK (quantity > 0),
    unit_price NUMERIC(10, 2) NOT NULL CHECK (unit_price >= 0),
    line_total NUMERIC(12, 2) NOT NULL CHECK (line_total >= 0),
    CONSTRAINT fk_sale_items_sale    FOREIGN KEY (sale_id)    REFERENCES sales (id)    ON DELETE CASCADE,
    CONSTRAINT fk_sale_items_product FOREIGN KEY (product_id) REFERENCES products (id) ON DELETE RESTRICT
);
CREATE INDEX idx_sale_items_sale    ON sale_items (sale_id);
CREATE INDEX idx_sale_items_product ON sale_items (product_id);

